static uint8_t rows[95][8];
static int rows_made;

/* Turns the written shapes into rows of bits, once. */
static void make_rows(void)
{
    int c;
    for (c = 0; c < 95; c++) {
        const char *s = shapes[c];
        int row = 0, col = 0;
        memset(rows[c], 0, sizeof(rows[c]));
        for (; *s && row < 8; s++) {
            if (*s == ' ') {
                row++;
                col = 0;
            } else {
                if (*s == '#' && col < 5)
                    rows[c][row] |= (uint8_t)(0x10u >> col);
                col++;
            }
        }
    }
    rows_made = 1;
}

const uint8_t *pc_font_glyph(unsigned char c)
{
    if (!rows_made)
        make_rows();
    if (c < 32 || c > 126)
        c = '?';
    return rows[c - 32];
}

int pc_font_draw(PcPicture *p, int x, int y, const char *text, uint32_t colour)
{
    for (; *text; text++, x += PC_FONT_CELL_W) {
        const uint8_t *g = pc_font_glyph((unsigned char)*text);
        int r, b;
        for (r = 0; r < 8; r++) {
            int py = y + r;
            if (py < 0 || py >= (int)p->height || !g[r])
                continue;
            for (b = 0; b < 5; b++) {
                int px = x + b;
                if ((g[r] & (0x10u >> b)) && px >= 0 && px < (int)p->width)
                    p->rgb[py][px] = colour;
            }
        }
    }
    return x;
}
